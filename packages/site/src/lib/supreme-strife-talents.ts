import talentsData from "@/autogenerated/sstalents.json";
import { defaultLocale, isLocale } from "@/i18n/config";

type TalentCatalogEntry = {
  name: Record<string, string | undefined>;
  description: Record<string, string | undefined>;
};

const talentCatalog = talentsData.talents as Record<string, TalentCatalogEntry | undefined>;

export function getSupremeStrifeTalents(ids?: readonly number[], locale?: string) {
  const targetLocale = isLocale(locale) ? locale : defaultLocale;

  return [...new Set(ids)].flatMap((id) => {
    const talent = talentCatalog[String(id)];
    if (!talent) {
      return [];
    }

    const name = talent.name[targetLocale] ?? talent.name[defaultLocale];
    const description = talent.description[targetLocale] ?? talent.description[defaultLocale];
    return name && description ? [{ id, name, description }] : [];
  });
}
