"use client";

import equipmentData from "@/autogenerated/equipment.json";

const equipmentMap = equipmentData.equipment.item;
const equipmentSlotMap = equipmentData.equipment.slot;

type EquipmentIdKey = keyof typeof equipmentMap;
type EquipmentSlotIdKey = keyof typeof equipmentSlotMap;

export function getEquipmentName(id: number | null | undefined) {
  if (typeof id !== "number" || !Number.isFinite(id)) {
    return undefined;
  }

  const equipment = equipmentMap[String(id) as EquipmentIdKey];
  if (!equipment) {
    return undefined;
  }

  return equipment.name;
}

export function getEquipmentSlotName(slot: number): string {
  return equipmentSlotMap[String(slot) as EquipmentSlotIdKey];
}
