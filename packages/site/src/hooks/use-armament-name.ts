"use client";

import armamentsData from "@/autogenerated/armaments.json";

type ArmamentDefinition = {
  name: string;
  percent?: boolean;
  icon?: {
    sprite: string;
    color: string;
  };
};

const armamentMap: Partial<Record<number, ArmamentDefinition>> = armamentsData.armaments;

export function getArmamentInfo(id: number | null | undefined) {
  if (typeof id !== "number" || !Number.isFinite(id)) {
    return undefined;
  }

  const armament = armamentMap[id];
  if (!armament) {
    return undefined;
  }

  const { name, icon } = armament;
  const percent = typeof armament.percent === "boolean" ? armament.percent : true;

  return name ? { name, percent, icon } : undefined;
}
