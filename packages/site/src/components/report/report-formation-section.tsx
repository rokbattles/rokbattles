import { cn } from "cn";
import Image from "next/image";
import armamentData from "@/autogenerated/armaments.json";
import { ReportInscriptionBadge } from "@/components/report/report-inscription-badge";
import { getFormationInfo } from "@/hooks/use-formation-name";
import { getGameSpriteUrl } from "@/lib/game-sprite";
import { parseArmamentInscriptions } from "@/lib/report/parsers";
import type { BattleCommanderArmament } from "@/lib/types/battle";

const emptyFormationSprite = "img_FormationSettingPattern_0.png";
const formationGround = getGameSpriteUrl("img_FormationSettingPageGrassland.png");

const slots = [
  {
    id: 1,
    name: "Scroll",
    emptySprite: "img_FormationSettingPattern_1.png",
    position: "col-start-1 row-start-1",
  },
  {
    id: 2,
    name: "Instrument",
    emptySprite: "img_FormationSettingPattern_4.png",
    position: "col-start-3 row-start-1",
  },
  {
    id: 3,
    name: "Flag",
    emptySprite: "img_FormationSettingPattern_3.png",
    position: "col-start-3 row-start-2",
  },
  {
    id: 4,
    name: "Emblem",
    emptySprite: "img_FormationSettingPattern_2.png",
    position: "col-start-1 row-start-2",
  },
] as const;

const formationGlow = cn(
  "bg-[#193745] [box-shadow:0_0_7px_1px_#67e8f999,0_0_16px_3px_#216fdb55]",
  "before:pointer-events-none before:absolute before:rounded-[inherit] before:border",
  "before:border-x-[#7ce8ff26] before:border-y-[#7ce8ff49] before:content-['']",
  "before:[inset:-4px_-3px] before:[transform:rotate(-28deg)]",
  "after:pointer-events-none after:absolute after:inset-0 after:rounded-[inherit] after:border",
  "after:border-[#b1f2fb] after:content-[''] after:[box-shadow:inset_0_0_6px_1px_#42e8ff80]"
);

const armamentGlow = cn(
  "[background:radial-gradient(ellipse_at_65%_85%,color-mix(in_srgb,var(--armament-light)_24%,#18161b),#1c191d_75%)]",
  "[border-color:color-mix(in_srgb,var(--armament-light)_78%,transparent)]",
  "[box-shadow:inset_0_0_8px_color-mix(in_srgb,var(--armament-light)_48%,transparent),0_0_10px_color-mix(in_srgb,var(--armament-light)_32%,transparent)]",
  "after:pointer-events-none after:absolute after:rounded-[inherit] after:border",
  "after:border-x-transparent after:content-['']",
  "after:[border-block-color:color-mix(in_srgb,var(--armament-light)_65%,white)]",
  "after:[inset:-2px_-1px] after:[transform:rotate(38deg)]"
);

const rarityStyles = {
  elite: "[--armament-light:#51cfff]",
  epic: "[--armament-light:#b45bff]",
  legendary: "[--armament-light:#ffbf3d]",
};

type ArmamentRarity = keyof typeof rarityStyles;
type ArmamentClass = { sprite: string; level?: number };

const rarities = armamentData.rarities as Partial<Record<number, ArmamentRarity>>;
const classes: Partial<Record<number, ArmamentClass>> = armamentData.classes;

type ReportFormationSectionProps = {
  formation?: number;
  armaments?: readonly BattleCommanderArmament[];
};

export function ReportFormationSection({ formation, armaments }: ReportFormationSectionProps) {
  const formationInfo = getFormationInfo(formation);
  const hasFormation = (formation ?? 0) > 0;
  const formationName = formationInfo?.name ?? `Unknown Formation ${formation}`;
  const [formationTitle, formationLevel = ""] = formationName.split(" Formation", 2);

  const formationSprite = formationInfo?.sprite;
  const formationSpriteUrl = getGameSpriteUrl(formationSprite ?? emptyFormationSprite);

  const loadout = slots.map((slot) => ({
    slot,
    armament: armaments?.find((item) => item.id === slot.id),
  }));

  const inscriptions = loadout.flatMap(({ slot, armament }) =>
    parseArmamentInscriptions(armament?.affix).map((id) => ({ id, key: `${slot.id}-${id}` }))
  );

  return (
    <section
      aria-label="Formation and armaments"
      className="mx-auto w-full max-w-58 min-w-0 space-y-1.5"
    >
      <div
        aria-label="Formation and armament slots"
        role="group"
        className="grid grid-cols-[minmax(0,1fr)_5.5rem_minmax(0,1fr)] grid-rows-2 place-items-center gap-x-1 gap-y-14 py-2"
      >
        <div className="relative col-start-2 row-span-2 row-start-1">
          <div
            className={cn(
              "relative isolate grid size-22 place-items-center rounded-full",
              formationSprite ? formationGlow : "border border-white/10"
            )}
          >
            {formationSprite ? (
              <Image
                src={formationGround}
                alt=""
                width={88}
                height={88}
                className="absolute inset-0 size-full rounded-full object-cover"
                unoptimized
                draggable={false}
              />
            ) : null}
            <Image
              src={formationSpriteUrl}
              alt={hasFormation ? "" : "No formation"}
              width={88}
              height={88}
              className={cn(
                "relative object-contain",
                formationSprite ? "size-full" : "size-12 opacity-[.13]"
              )}
              unoptimized
              draggable={false}
            />
          </div>
          {hasFormation ? (
            <p className="absolute inset-x-[-0.75rem] top-full pt-2 text-center text-xs font-medium whitespace-nowrap text-zinc-300">
              {formationTitle}
              <br />
              Formation{formationLevel}
            </p>
          ) : null}
        </div>
        {loadout.map(({ slot, armament }) => (
          <ArmamentSlot key={slot.id} slot={slot} armament={armament} />
        ))}
      </div>
      {inscriptions.length > 0 ? (
        <ul aria-label="Inscriptions" className="grid grid-cols-2 gap-x-2 gap-y-1.5">
          {inscriptions.map(({ id, key }) => (
            <li key={key} className="flex min-w-0 justify-center">
              <ReportInscriptionBadge id={id} />
            </li>
          ))}
        </ul>
      ) : null}
    </section>
  );
}

function ArmamentSlot({
  slot,
  armament,
}: {
  slot: (typeof slots)[number];
  armament?: BattleCommanderArmament;
}) {
  const configuration = armament?.configuration;
  const rarity = configuration == null ? undefined : rarities[configuration];
  // The class ID is the configuration ID without its last three digits.
  const armamentClass =
    configuration == null ? undefined : classes[Math.floor(configuration / 1000)];
  const level = armamentClass?.level;

  const slotLabel = armament ? slot.name : `Empty ${slot.name} slot`;
  const label = rarity
    ? `${rarity.charAt(0).toUpperCase()}${rarity.slice(1)} ${slotLabel}`
    : slotLabel;
  const description = level ? `${label}, formation level ${level}` : label;

  const slotStyle = rarity ? cn(armamentGlow, rarityStyles[rarity]) : "border-white/10";

  return (
    <div
      className={cn(
        "relative grid size-15 place-items-center rounded-full border",
        slot.position,
        slotStyle
      )}
      role="img"
      aria-label={description}
      title={description}
    >
      <Image
        src={getGameSpriteUrl(armamentClass?.sprite ?? slot.emptySprite)}
        alt=""
        width={56}
        height={56}
        className={cn("object-contain", armamentClass ? "size-[88%]" : "size-[58%] opacity-[.13]")}
        unoptimized
        draggable={false}
      />
      {level ? (
        <Image
          src={getGameSpriteUrl(`img_formation_LV_${level}.png`)}
          alt=""
          width={18}
          height={18}
          className="absolute bottom-0 left-1/2 -translate-x-1/2 translate-y-1/4"
          unoptimized
          draggable={false}
        />
      ) : null}
    </div>
  );
}
