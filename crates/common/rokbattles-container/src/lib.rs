//! Reads and writes ROKB containers with schema-specific payloads.
//!
//! Files use the `.bin` extension. Each file contains a 20-byte header followed by one masked payload. The
//! header identifies the schema, seed, payload length, and checksum. Readers
//! validate the envelope before interpreting the payload.
//!
//! Enable `read` for the Rust reader, `write` for the writers, or `wasm-read`
//! for JavaScript bindings to the same reader. The default features are `read`
//! and `write`. Built-in schemas support bytes, UTF-8 text, and JSON; callers
//! supply the serialization and decoding logic for application schemas. Enable
//! `schemas` for territory planner schemas 401–403; `wasm-read` includes it.
//! Reserved schemas 1–3 do not require `schemas`.
//!
//! Masking is reversible using the public seed. CRC32 detects accidental
//! payload corruption; neither mechanism authenticates the file or restricts
//! access to its contents.
//!
//! # Examples
//!
//! Write a text payload and decode it using the schema ID in its header:
//!
//! ```
//! # #[cfg(all(feature = "read", feature = "write"))] {
//! use rokbattles_container::{Reader, Value, write_text};
//! let mut bytes = write_text("Hello, kingdom!", 42)?;
//! let decoded = Reader::default().decode(&mut bytes)?;
//! assert_eq!(decoded.value, Value::Text("Hello, kingdom!".into()));
//! # }
//! # Ok::<(), rokbattles_container::Error>(())
//! ```

#![deny(missing_docs)]
#![forbid(unsafe_code)]

mod error;
#[cfg(any(feature = "read", feature = "write"))]
mod mask;
#[cfg(feature = "read")]
mod read;
#[cfg(feature = "schemas")]
pub mod schemas;
#[cfg(feature = "wasm-read")]
pub mod wasm;
#[cfg(feature = "write")]
mod write;

pub use error::Error;
#[cfg(feature = "read")]
pub use read::{Decoded, Envelope, ReadLimits, Reader, Value};
#[cfg(feature = "write")]
pub use write::{write_bytes, write_envelope, write_json, write_text};

/// Four-byte file signature: ASCII `ROKB`.
pub const MAGIC: [u8; 4] = *b"ROKB";
/// Version of the envelope layout and transform rules.
pub const VERSION: u8 = 1;
/// Number of bytes before the payload.
pub const HEADER_LEN: usize = 20;
/// Built-in payload schema IDs, each identifying an exact byte layout.
pub mod schema {
    /// Arbitrary bytes, preserved exactly.
    pub const BYTES: u16 = 1;
    /// Strict UTF-8 text, without a length prefix or terminator.
    pub const TEXT: u16 = 2;
    /// One UTF-8 JSON value using serde_json's numeric model.
    pub const JSON: u16 = 3;
}

/// Parsed v1 header. Integers on the wire use little-endian byte order.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Header {
    /// Envelope version, currently 1.
    pub version: u8,
    /// Reserved for future use; must be zero.
    pub flags: u8,
    /// Payload layout identifier; zero is reserved and invalid.
    pub schema_id: u16,
    /// Public seed used by both mandatory masking stages.
    pub seed: u32,
    /// Length of the payload, excluding the header.
    pub payload_len: u32,
    /// IEEE CRC32 of the unmasked payload only.
    pub crc32: u32,
}

