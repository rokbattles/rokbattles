/// Returns the language keys for the title, subtitle, and body.
pub(crate) fn bundle_keys(param: i64, purchase_title: Option<&str>) -> BundleKeys {
    let Some((_, keys)) = BUNDLE_KEYS.iter().find(|(number, _)| *number == param) else {
        return ["", "", ""];
    };
    let [title, subtitle, mut content] = *keys;
    if purchase_title == Some("LC_EVENT_AVATARGACHA_IAP_TAB") {
        content = "LC_MAIL_RECHARGE_NOGEM_CONTENT";
    }
    [title, subtitle, content]
}
