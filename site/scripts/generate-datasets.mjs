import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseAllDocuments } from "yaml";

const scriptDir = fileURLToPath(new URL(".", import.meta.url));
const repoRoot = path.resolve(scriptDir, "../..");
const datasetsDir = path.join(repoRoot, "datasets");
const outputDir = path.resolve(scriptDir, "../src/autogenerated");

const isYamlFile = (name) => {
  const ext = path.extname(name).toLowerCase();
  return ext === ".yaml";
};

const parseYaml = (raw) => {
  const docs = parseAllDocuments(raw);

  if (docs.length === 0) return null;
  if (docs.length === 1) return docs[0]?.toJSON?.() ?? null;

  return docs.map((d) => d.toJSON());
};

const toJsonName = (yamlName) => `${path.basename(yamlName, path.extname(yamlName))}.json`;

async function generate() {
  await mkdir(outputDir, { recursive: true });

  const entries = await readdir(datasetsDir, { withFileTypes: true });
  const yamlNames = entries.filter((e) => e.isFile() && isYamlFile(e.name)).map((e) => e.name);

  await Promise.all(
    yamlNames.map(async (name) => {
      const raw = await readFile(path.join(datasetsDir, name), "utf8");
      const parsed = parseYaml(raw);
      await writeFile(
        path.join(outputDir, toJsonName(name)),
        `${JSON.stringify(parsed)}\n`,
        "utf8"
      );
    })
  );

  console.log("Success");
}

await generate();
